const Glyph &digit(char d) {
    static const Glyph digits[] = {
        {5, {".###.", "#...#", "#...#", "#...#", "#...#", ".###."}},
        {3, {".#.", "##.", ".#.", ".#.", ".#.", "###"}}, // the font's
        {5, {".###.", "#...#", "...#.", "..#..", ".#...", "#####"}},
        {5, {"####.", "....#", ".###.", "....#", "....#", "####."}}, // the font's
        {5, {"...#.", "..##.", ".#.#.", "#####", "...#.", "...#."}},
        {5, {"#####", "#....", "####.", "....#", "....#", "####."}},
        {5, {".###.", "#....", "####.", "#...#", "#...#", ".###."}},
        {5, {"#####", "....#", "...#.", "..#..", "..#..", "..#.."}},
        {5, {".###.", "#...#", ".###.", "#...#", "#...#", ".###."}},
        {5, {".###.", "#...#", "#...#", ".####", "....#", ".###."}},
    };
    return digits[d >= '0' && d <= '9' ? d - '0' : 0];
}

int width(const std::string &digits) {
    int w = 0;
    for (char d : digits) w += digit(d).width + 1;
    return w ? w - 1 : 0;
}

